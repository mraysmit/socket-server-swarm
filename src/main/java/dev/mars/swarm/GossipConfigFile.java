package dev.mars.swarm;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Properties;
import java.util.regex.Pattern;

/**
 * The properties file the gossip plugin reads when each server starts. Its path is the JVM-wide {@code gossip.config}
 * property, set while this object is open. Every server gets {@code server.<id>.} overrides for its swarm ID and seed,
 * because one file serves all swarms in the JVM.
 */
final class GossipConfigFile implements AutoCloseable {
    static final String PROPERTY = "gossip.config";
    private final String advertiseHost;
    private final Path file;
    private final Properties entries = new Properties();
    private boolean closed;

    GossipConfigFile(GossipSettings settings) throws IOException {
        advertiseHost = settings.advertiseHost();
        entries.setProperty("advertise.host", advertiseHost);
        settings.options().forEach(entries::setProperty);
        file = Files.createTempFile("swarm-gossip-", ".properties");
        write();
        System.setProperty(PROPERTY, file.toString());
    }

    /** Declares every server of a swarm before any starts, so each knows its swarm ID. */
    synchronized void declare(String swarm, int count) throws IOException {
        for (int i = 1; i <= count; i++) { entries.setProperty(prefix(swarm, i) + "swarm.id", swarm); }
        write();
    }

    /** Points servers 2 and up at the first server, which is already listening on the given port. */
    synchronized void seedFirstServer(String swarm, int count, int port) throws IOException {
        String host = advertiseHost.contains(":") ? "[" + advertiseHost + "]" : advertiseHost;
        for (int i = 2; i <= count; i++) {
            entries.setProperty(prefix(swarm, i) + "seeds", id(swarm, 1) + "@" + host + ":" + port);
        }
        write();
    }

    /** Declares one server added to a running swarm, seeded at a server that is already in it. */
    synchronized void declareServer(String swarm, int index, String seedId, int seedPort) throws IOException {
        String host = advertiseHost.contains(":") ? "[" + advertiseHost + "]" : advertiseHost;
        entries.setProperty(prefix(swarm, index) + "swarm.id", swarm);
        entries.setProperty(prefix(swarm, index) + "seeds", seedId + "@" + host + ":" + seedPort);
        write();
    }

    /** Drops one server's entries once it is removed from its swarm. Best effort, like {@link #forget}. */
    synchronized void forgetServer(String serverId) {
        for (var key : java.util.List.copyOf(entries.stringPropertyNames())) {
            if (key.startsWith("server." + serverId + ".")) { entries.remove(key); }
        }
        try { write(); } catch (IOException ignored) { /* the file is only read when a server starts */ }
    }

    /** Drops a swarm's entries once it is stopped or failed to start. Best effort: running servers never re-read the file. */
    synchronized void forget(String swarm) {
        var own = Pattern.compile("server\\." + Pattern.quote(swarm) + "-Server-\\d{3}\\..*");
        for (var key : java.util.List.copyOf(entries.stringPropertyNames())) {
            if (own.matcher(key).matches()) { entries.remove(key); }
        }
        try { write(); } catch (IOException ignored) { /* the file is only read when a server starts */ }
    }

    @Override public synchronized void close() throws IOException {
        if (closed) { return; }
        closed = true;
        if (file.toString().equals(System.getProperty(PROPERTY))) { System.clearProperty(PROPERTY); }
        Files.deleteIfExists(file);
    }

    static String id(String swarm, int index) { return swarm + "-Server-" + String.format(java.util.Locale.ROOT, "%03d", index); }
    private static String prefix(String swarm, int index) { return "server." + id(swarm, index) + "."; }

    private void write() throws IOException {
        try (var out = Files.newBufferedWriter(file, StandardCharsets.UTF_8)) { entries.store(out, "Generated by SwarmManager"); }
    }
}
